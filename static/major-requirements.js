  function majorFitPadding() {
    return state.mobile ? 34 : 64;
  }

  function updateMajorFitMinimum() {
    var visible = majorFitElements();
    if (!visible || !visible.length) return null;
    if (window.GraphInteractionSupport) {
      return window.GraphInteractionSupport.updateFitMinimum(
        state.cy,
        visible,
        majorFitPadding()
      );
    }
    state.cy.fit(visible, majorFitPadding());
    state.cy.minZoom(state.cy.zoom());
    return { zoom: state.cy.zoom(), pan: state.cy.pan() };
  }

  function fitMajorGraph(duration) {
    var visible = majorFitElements();
    if (!visible || !visible.length) return;
    if (window.GraphInteractionSupport) {
      window.GraphInteractionSupport.fitToMinimum(
        state.cy,
        visible,
        majorFitPadding(),
        duration || 0
      );
    } else {
      updateMajorFitMinimum();
    }
  }

  function renderGraph() {
    if (typeof window.cytoscape !== "function") {
      elements.graphEmpty.hidden = false;
      return;
    }
    state.cy = window.cytoscape({
      container: elements.graphCanvas,
      elements: graphElements(),
      style: graphStyles(),
      layout: { name: "preset", fit: false },
      minZoom: 0.01,
      maxZoom: 2.4,
      boxSelectionEnabled: false,
      autoungrabify: true
    });
    state.tapSuppressor.reset();
    if (window.GraphInteractionSupport) {
      window.GraphInteractionSupport.bindNodeCursor(elements.graphStage, state.cy, completionHit);
    }
    applyRelationFilters();
    fitMajorGraph(0);
    var readableZoom = state.mobile ? 0.58 : 0.5;
    if (state.cy.zoom() < readableZoom) {
      var majorRequirements = state.cy.nodes(".major-course, .requirement-summary, .requirement-group");
      state.cy.zoom(readableZoom);
      state.cy.center(majorRequirements);
    }
    state.cy.on("mouseover", "node.course", function (event) {
      if (!state.hover.enter(event.target.id()).apply) return;
      applyHover(event.target);
    });
    state.cy.on("mouseout", "node.course", function () {
      if (!state.hover.leave().apply) return;
      clearHover();
    });
    state.cy.on("tap", "node.course", function (event) {
      if (state.tapSuppressor.consumesTap(event.target.id())) return;
      if (completionHit(event.target, event.renderedPosition)) event.stopPropagation();
      activateCourseNode(event.target, event.renderedPosition, false);
    });
    // On mobile, holding a node is the "click": it opens the course drawer.
    // This runs before the trailing tap on release, which is then suppressed.
    state.cy.on("taphold", "node.course", function (event) {
      if (!state.mobile) return;
      if (completionHit(event.target, event.renderedPosition)) return;
      state.tapSuppressor.suppress(event.target.id());
      event.stopPropagation();
      activateCourseNode(event.target, event.renderedPosition, true);
    });
    // A new press starts a fresh gesture: any long-press tap that never arrived
    // (because the finger drifted into a pan) must not swallow this one.
    state.cy.on("tapstart", function () {
      state.tapSuppressor.beginGesture();
    });
    // Clicking empty canvas releases a pinned highlight ("click elsewhere").
    state.cy.on("tap", function (event) {
      if (event.target !== state.cy) return;
      releasePinnedHover();
    });
  }

  function relationLabel(relation) {
    return relation === "prerequisite" ? "Prerequisite" : relation === "corequisite" ? "Corequisite" : "Exclusion";
  }

  function fallbackRequirements(item) {
    var byRelation = new Map(item.requirements.map(function (requirement) {
      return [requirement.relation, requirement.raw];
    }));
    return ["prerequisite", "corequisite", "exclusion"].map(function (relation) {
      return { relation: relation, raw: byRelation.get(relation) || "" };
    });
  }

  function renderCourseDrawer(item, detail) {
    var requirements = detail && detail.requirements
      ? ["prerequisite", "corequisite", "exclusion"].map(function (relation) {
          var requirement = detail.requirements[relation];
          return { relation: relation, raw: requirement && (requirement.raw || requirement.raw_text) || "" };
        })
      : fallbackRequirements(item);
    var requirementMarkup = requirements.map(function (requirement) {
      var empty = !requirement.raw;
      return '<section class="requirement-section' + (empty ? " is-empty" : "") + '"><h3><span class="requirement-indicator ' +
        escapeHtml(requirement.relation) + '"></span>' + relationLabel(requirement.relation) +
        '</h3><p>' + escapeHtml(requirement.raw || "None listed") + "</p></section>";
    }).join("");
    var rawCredits = detail && detail.credits != null ? String(detail.credits) : item.credits;
    var creditText = /credit/i.test(rawCredits) ? rawCredits : rawCredits ? rawCredits + " credits" : "";
    var source = detail && (detail.source_url || detail.sourceUrl) || item.source;
    var completed = state.completions.has(item.code);
    elements.drawerContent.innerHTML =
      '<h3 class="details-title">' + escapeHtml(detail && detail.title || item.title) + "</h3>" +
      '<div class="details-meta"><span class="meta-chip">' + escapeHtml(DATA.intake) + " intake</span>" +
      (creditText ? '<span class="meta-chip">' + escapeHtml(creditText) + "</span>" : "") +
      '<span class="meta-chip">' + (item.major ? "Counts toward major" : "Context only") + "</span></div>" +
      '<label class="complete-control"><span>Completed</span><span class="switch"><input id="majorCompletedToggle" type="checkbox" ' +
      (completed ? "checked" : "") + '><span></span></span></label>' +
      requirementMarkup +
      (source ? '<a class="source-link" href="' + escapeHtml(source) + '" target="_blank" rel="noreferrer">Open official course entry</a>' : "");
    var toggle = document.getElementById("majorCompletedToggle");
    if (toggle) {
      toggle.addEventListener("change", function () {
        setCourseCompletion(item.code, toggle.checked);
      });
    }
  }

  async function openCourse(code) {
    var item = courseByCode.get(code);
    if (!item) return;
    elements.drawerSubject.textContent = item.major
      ? (DATA.programCode || "Major") + " major course"
      : "Relationship context";
    elements.drawerCode.textContent = item.code;
    renderCourseDrawer(item, state.detailCache.get(code));
    openDrawer();
    if (state.detailCache.has(code)) return;
    var requestId = ++state.detailRequest;
    try {
      var detail = window.HKUSTCatalog
        ? await window.HKUSTCatalog.course(CATALOG_YEAR, code)
        : null;
      if (!detail) return;
      state.detailCache.set(code, detail);
      if (requestId === state.detailRequest && elements.drawerCode.textContent === code) {
        renderCourseDrawer(item, detail);
      }
    } catch (_error) {
      // Static PDF/catalog text remains available when the catalog is unavailable.
    }
  }

  function openDrawer() {
    elements.drawer.classList.add("is-open");
    elements.drawer.setAttribute("aria-hidden", "false");
    elements.drawerScrim.hidden = !state.mobile;
  }

  function closeDrawer() {
    elements.drawer.classList.remove("is-open");
    elements.drawer.setAttribute("aria-hidden", "true");
    elements.drawerScrim.hidden = true;
    if (state.cy) state.cy.nodes().unselect();
  }

  function courseButton(code, title, credits) {
    return '<button type="button" data-major-code="' + escapeHtml(code) + '"><span class="major-outline-code">' +
      escapeHtml(code) + '</span><span class="major-outline-title">' + escapeHtml(title) +
      '</span><span class="major-outline-credit">' + escapeHtml(credits) + " cr</span></button>";
  }

  function outlineCourses(section) {
    return majorCourses.filter(function (item) { return item.section === section.id; });
  }

  function branchKindLabel(kind) {
    var labels = {
      option: "Option",
      track: "Track",
      stream: "Stream",
      specialization: "Specialization",
      concentration: "Concentration",
      area: "Area",
      courses: "Course list",
      group: "Requirement group",
      other: "Branch"
    };
    return labels[kind] || "Branch";
  }

  function branchDepth(branch, byId) {
    var depth = 0;
    var cursor = branch;
    while (cursor && cursor.parent && byId.has(cursor.parent) && depth < 12) {
      depth += 1;
      cursor = byId.get(cursor.parent);
    }
    return depth;
  }

  function branchCourseButton(course) {
    var credit = course.credits ? escapeHtml(course.credits) + " cr" : "";
    return '<button type="button" data-major-code="' + escapeHtml(course.code) + '"><span class="major-outline-code">' +
      escapeHtml(course.code) + '</span><span class="major-outline-title">' + escapeHtml(course.title) +
      '</span><span class="major-outline-credit">' + credit + "</span></button>";
  }

  // Branches are the option/track/area tables that follow the core requirement
  // sections (e.g. CPEG's AI, robotics and VLSI areas). They are captured
  // verbatim so the outline can show the available areas and their courses.
  function renderBranches() {
    if (!BRANCHES.length) return "";
    var byId = new Map(BRANCHES.map(function (branch) { return [branch.id, branch]; }));
    var items = BRANCHES.map(function (branch) {
      var depth = branchDepth(branch, byId);
      var courses = branch.courses.map(branchCourseButton).join("");
      var header = '<header><div><p class="eyebrow">' + escapeHtml(branchKindLabel(branch.kind)) +
        (branch.group ? " &middot; " + escapeHtml(branch.group) : "") + '</p><h4>' +
        escapeHtml(branch.title) + "</h4></div>" +
        (branch.credits ? "<strong>" + escapeHtml(branch.credits) + " cr</strong>" : "") + "</header>";
      var rule = branch.rule ? '<p class="major-rule-copy">' + escapeHtml(branch.rule) + "</p>" : "";
      var list = courses ? '<div class="major-outline-list">' + courses + "</div>" : "";
      return '<section class="major-branch" data-depth="' + depth + '">' + header + rule + list + "</section>";
    }).join("");
    return '<section class="major-outline-section major-branches-section">' +
      '<header><div><p class="eyebrow">Areas &amp; options</p><h3>Branches</h3></div></header>' +
      '<p class="major-rule-copy">Tracks, streams, options and specialization areas listed for this program.</p>' +
      '<div class="major-branch-list">' + items + "</div></section>";
  }

  function renderOutline() {
    var sections = DATA.sections || [];
    var core = sections.map(function (section) {
      var list = outlineCourses(section).map(function (item) {
        return courseButton(item.code, item.title, item.credits);
      }).join("");
      var header = '<header><div><p class="eyebrow">' + escapeHtml(section.eyebrow) +
        '</p><h3>' + escapeHtml(section.title) + '</h3></div><strong>' +
        escapeHtml(section.credits) + '</strong></header>';
      var link = section.sourceLink
        ? '<a class="source-link" href="' + escapeHtml(PROGRAM_SOURCE) +
          '" target="_blank" rel="noreferrer">' + escapeHtml(section.sourceLink) + "</a>"
        : "";
      var copy = section.copy ? '<p class="major-rule-copy">' + escapeHtml(section.copy) + "</p>" : "";
      return '<section class="major-outline-section">' + header +
        copy +
        '<div class="major-outline-list">' + list + "</div>" + link + "</section>";
    }).join("");
    var empty = !sections.length
      ? '<p class="major-outline-empty">This program publishes only elective requirements, so no mandatory core courses are listed.</p>'
      : "";
    elements.outlineContent.innerHTML = empty + core + renderBranches();
  }

  function setView(view) {
    var graph = view === "graph";
    elements.graphPanel.hidden = !graph;
    elements.outlinePanel.hidden = graph;
    elements.graphTab.classList.toggle("is-active", graph);
    elements.outlineTab.classList.toggle("is-active", !graph);
    elements.graphTab.setAttribute("aria-selected", String(graph));
    elements.outlineTab.setAttribute("aria-selected", String(!graph));
    if (graph && state.cy) {
      state.cy.resize();
      updateMajorFitMinimum();
    }
  }

  function bindEvents() {
    if (window.GraphInteractionSupport) {
      window.GraphInteractionSupport.bindRightDragPan(elements.graphCanvas, function () {
        return state.cy;
      });
    }
    elements.relationInputs.forEach(function (input) { input.addEventListener("change", applyRelationFilters); });
    elements.graphTab.addEventListener("click", function () { setView("graph"); });
    elements.outlineTab.addEventListener("click", function () { setView("outline"); });
    elements.zoomIn.addEventListener("click", function () {
      if (state.cy) state.cy.animate({ zoom: Math.min(2.4, state.cy.zoom() * 1.2), duration: 120 });
    });
    elements.zoomOut.addEventListener("click", function () {
      if (state.cy) state.cy.animate({ zoom: Math.max(state.cy.minZoom(), state.cy.zoom() / 1.2), duration: 120 });
    });
    elements.fit.addEventListener("click", function () {
      fitMajorGraph(180);
    });
    elements.closeDrawer.addEventListener("click", closeDrawer);
    elements.drawerScrim.addEventListener("click", closeDrawer);
    if (elements.majorSelect) {
      elements.majorSelect.addEventListener("change", function (event) {
        loadProgram(event.target.value);
      });
    }
    elements.outlineContent.addEventListener("click", function (event) {
      var button = event.target.closest("[data-major-code]");
      if (button) openCourse(button.dataset.majorCode);
    });
    // Completion checkboxes are shared with the Course/USTree pages through
    // localStorage; pick up changes made in another open tab.
    window.addEventListener("storage", function (event) {
      if (event.key !== completionKey()) return;
      loadCompletions();
      if (state.cy) renderGraph();
      renderOutline();
      var toggle = document.getElementById("majorCompletedToggle");
      if (toggle) toggle.checked = state.completions.has(normalizeCode(elements.drawerCode.textContent));
    });
    document.addEventListener("keydown", function (event) {
      if (event.key !== "Escape") return;
      closeDrawer();
      releasePinnedHover();
    });
    var mobileQuery = window.matchMedia(MOBILE_QUERY);
    mobileQuery.addEventListener("change", function (event) {
      state.mobile = event.matches;
      if (state.cy) {
        state.cy.resize();
        updateMajorFitMinimum();
      }
      if (!state.mobile) elements.drawerScrim.hidden = true;
    });
    window.addEventListener("resize", function () {
      state.mobile = mobileQuery.matches;
      if (state.cy) {
        state.cy.resize();
        updateMajorFitMinimum();
        window.requestAnimationFrame(function () {
          if (!state.cy) return;
          state.cy.resize();
          updateMajorFitMinimum();
        });
      }
    });
    // Zen mode hides the chrome, so the map must grow to the new viewport and
    // re-fit (toggling the body class never fires a window resize).
    window.addEventListener("hkust-zen-change", function () {
      if (!state.cy) return;
      state.cy.resize();
      window.requestAnimationFrame(function () {
        if (!state.cy) return;
        state.cy.resize();
        updateMajorFitMinimum();
        fitMajorGraph(180);
      });
    });
  }

  function updateHeader() {
    var outline = DATA.outline || {};
    var eyebrow = document.querySelector("#majorOutlinePanel .outline-header .eyebrow");
    var title = document.querySelector("#majorOutlinePanel .outline-header h2");
    var credits = document.querySelector("#majorOutlinePanel .outline-header > p");
    if (eyebrow && outline.eyebrow) eyebrow.textContent = outline.eyebrow;
    if (title && outline.title) title.textContent = outline.title;
    if (credits && outline.credits) credits.textContent = outline.credits;
    var tagline = document.querySelector(".major-topbar .brand-block p");
    if (tagline) tagline.textContent = "Major requirements | " + (DATA.totalCredits || "");
    if (elements.majorSelect && DATA.id) elements.majorSelect.value = DATA.id;
    document.title = (DATA.programCode || "Major") + " Major Requirements | HKUST Course Tree";
  }

  function populateSelector(manifest) {
    if (!elements.majorSelect) return;
    var programs = (manifest.programs || []).slice().sort(function (a, b) {
      return (a.programCode || "").localeCompare(b.programCode || "");
    });
    elements.majorSelect.innerHTML = programs.map(function (program) {
      return '<option value="' + escapeHtml(program.id) + '">' +
        escapeHtml(program.programCode + " (" + program.intake + ")") + "</option>";
    }).join("");
  }

  function programFile(program) {
    if (program && program.file) return program.file;
    return MAJOR_DIR_URL + program.id + ".json";
  }

  function loadProgram(id) {
    if (!MANIFEST) return;
    var program = (MANIFEST.programs || []).filter(function (entry) {
      return entry.id === id;
    })[0];
    if (!program) return;
    if (state.cy) {
      state.cy.destroy();
      state.cy = null;
    }
    if (elements.graphCanvas) elements.graphCanvas.hidden = false;
    if (elements.graphEmpty) elements.graphEmpty.hidden = true;
    window.fetch(programFile(program), { cache: "no-store" })
      .then(function (response) {
        if (!response.ok) throw new Error("HTTP " + response.status + " loading " + programFile(program));
        return response.json();
      })
      .then(function (data) {
        applyData(data);
        updateHeader();
        renderOutline();
        renderGraph();
      })
      .catch(showLoadError);
  }

  function showLoadError(error) {
    if (elements.graphCanvas) elements.graphCanvas.hidden = true;
    if (elements.graphEmpty) {
      elements.graphEmpty.hidden = false;
      elements.graphEmpty.innerHTML = "<strong>Major requirement data unavailable</strong>" +
        "<span>" + escapeHtml(error && error.message ? error.message : String(error)) + "</span>";
    }
  }

  // Re-read an imported snapshot after the transfer module merged it into
  // localStorage. With a program in the file, (re)load it so the selector, the
  // outline, the map, and the completion checkboxes all follow; otherwise just
  // refresh the checkbox state for the current program.
  function applyImportedData(summary) {
    if (summary && summary.preferences && summary.preferences.indexOf("theme") !== -1 &&
        window.HKUSTTheme && window.HKUSTDataTransfer && window.HKUSTDataTransfer.loadTheme) {
      var theme = window.HKUSTDataTransfer.loadTheme(localStorage);
      if (theme) window.HKUSTTheme.set(theme);
    }
    var importedId = summary && summary.major && summary.major.id;
    var known = importedId && (MANIFEST && MANIFEST.programs || []).some(function (entry) {
      return entry.id === importedId;
    });
    if (known) {
      loadProgram(importedId);
      return;
    }
    loadCompletions();
    if (state.cy) renderGraph();
    renderOutline();
  }

  function bindDataTransfer() {
    if (!window.HKUSTDataTransfer || typeof window.HKUSTDataTransfer.bind !== "function") return;
    window.HKUSTDataTransfer.bind({
      // A legacy year-less file lands on the catalog year of the loaded program.
      year: function () { return CATALOG_YEAR; },
      onApplied: applyImportedData
    });
  }

  function bootstrap() {
    if (typeof window.fetch !== "function") {
      showLoadError(new Error("This browser cannot load " + MANIFEST_URL));
      return;
    }
    window.fetch(MANIFEST_URL, { cache: "no-store" })
      .then(function (response) {
        if (!response.ok) throw new Error("HTTP " + response.status + " loading " + MANIFEST_URL);
        return response.json();
      })
      .then(function (manifest) {
        MANIFEST = manifest;
        populateSelector(manifest);
        bindEvents();
        bindDataTransfer();
        var programs = manifest.programs || [];
        var stored = window.HKUSTDataTransfer && typeof window.HKUSTDataTransfer.loadSelectedMajor === "function"
          ? window.HKUSTDataTransfer.loadSelectedMajor(localStorage)
          : null;
        var storedProgram = stored && programs.filter(function (entry) { return entry.id === stored.id; })[0];
        var preferred = storedProgram ||
          programs.filter(function (entry) { return entry.programCode === "CPEG"; })[0] ||
          programs[0];
        if (!preferred) throw new Error("The major-requirement manifest lists no programs");
        loadProgram(preferred.id);
      })
      .catch(showLoadError);
  }

  bootstrap();
