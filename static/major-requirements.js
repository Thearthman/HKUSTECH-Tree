  function createHoverState() {
    if (SUPPORT.createHoverState) return SUPPORT.createHoverState();
    // Minimal fallback mirroring static/graph-interactions.js createHoverState().
    var pinned = null;
    var hovered = null;
    function decision(apply, id) { return { apply: apply, id: id }; }
    return {
      pinnedId: function () { return pinned; },
      activeId: function () { return pinned || hovered; },
      isPinned: function () { return pinned != null; },
      enter: function (id) {
        if (pinned != null) return decision(false, pinned);
        hovered = id == null ? null : String(id);
        return decision(true, hovered);
      },
      leave: function () {
        if (pinned != null) return decision(false, pinned);
        hovered = null;
        return decision(true, null);
      },
      pin: function (id) {
        pinned = id == null ? null : String(id);
        hovered = pinned;
        return decision(true, pinned);
      },
      release: function () {
        if (pinned == null && hovered == null) return decision(false, null);
        pinned = null;
        hovered = null;
        return decision(true, null);
      },
      reset: function () { pinned = null; hovered = null; }
    };
  }

  function createTapSuppressor() {
    if (SUPPORT.createTapSuppressor) return SUPPORT.createTapSuppressor();
    // Minimal fallback mirroring static/graph-interactions.js createTapSuppressor().
    var suppressed = null;
    function same(a, b) {
      return (a == null ? null : String(a)) === (b == null ? null : String(b));
    }
    return {
      suppress: function (id) { suppressed = id == null ? null : String(id); },
      beginGesture: function () { suppressed = null; },
      consumesTap: function (id) {
        if (suppressed == null || !same(suppressed, id)) return false;
        suppressed = null;
        return true;
      },
      reset: function () { suppressed = null; }
    };
  }

